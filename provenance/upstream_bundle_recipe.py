"""Combine verified solution sources in dependency order for one native check.

File sections keep local options, variables and opened names scoped as in the
original modules. The namespace and theorem names are unchanged. No comparator
statement templates enter the bundle.
"""
import hashlib
import json
import pathlib
import re

BASE = pathlib.Path(__file__).resolve().parent
manifest = json.loads((BASE / "source_manifest.json").read_text(encoding="utf-8"))
records = {r["module"]: r for r in manifest["modules"]}
ordered = []
seen = set()


def visit(module):
    if module in seen:
        return
    seen.add(module)
    for dependency in records[module]["imports"]:
        visit(dependency)
    ordered.append(module)


visit(manifest["root_module"])
mathlib_imports = [
    "Mathlib.Tactic", "Mathlib.RingTheory.RootsOfUnity.Complex",
    "Mathlib.LinearAlgebra.Matrix.NonsingularInverse",
    "Mathlib.LinearAlgebra.Matrix.Determinant.Misc", "Mathlib.Data.Matrix.Block",
    "Mathlib.LinearAlgebra.Matrix.Block", "Mathlib.Analysis.SpecialFunctions.Log.Base",
    "Mathlib.Analysis.SpecialFunctions.Log.RpowTendsto",
    "Mathlib.Analysis.SpecialFunctions.Pow.Asymptotics",
    "Mathlib.Analysis.Asymptotics.SpecificAsymptotics",
    "Mathlib.Data.Nat.Choose.Factorization", "Mathlib.NumberTheory.PrimeCounting",
    "Mathlib.Data.Nat.Log", "Mathlib.Data.Nat.ChineseRemainder",
    "Mathlib.Data.Nat.Digits.Lemmas", "Mathlib.Data.ZMod.Coprime",
    "Mathlib.Data.Fintype.Pi", "Mathlib.Data.Fintype.BigOperators",
    "Mathlib.Data.Fin.Tuple.Basic", "Mathlib.Data.Finset.Sort",
    "Mathlib.Data.Finset.Powerset", "Mathlib.Algebra.BigOperators.Fin",
    "Mathlib.Algebra.Order.Floor.Semifield",
]
chunks = ["".join(f"import {m}\n" for m in mathlib_imports) +
          "\nset_option maxErrors 500\n\n/-! Pinned third-party OpenAI Fourier solution sources.\n"
          "Repository: https://github.com/openai/math\n"
          f"Commit: {manifest['commit']}\n"
          "License: Apache-2.0; see LICENSE in references/openai_uniform_fourier.\n"
          "Generated by build_bundle.py; compilation and axiom checks are separate.\n"
          "Lean/mathlib 4.29.1 compatibility edits are listed in compatibility_manifest.json. -/\n"]
compatibility = []
prelude = BASE.parents[1] / "formalization" / "vendor" / "PrimeCountingCompatibility.lean"
if prelude.exists():
    prelude_data = prelude.read_bytes()
    prelude_source = re.sub(r"^import[^\n]*\n", "", prelude_data.decode("utf-8"), flags=re.M)
    if re.search(r"\b(sorry|admit)\b|^axiom\s", prelude_source, re.M):
        raise ValueError("Unproved compatibility declaration")
    chunks.append("\nsection\n" + prelude_source + "\nend\n")
    compatibility.append({"prelude": str(prelude.relative_to(BASE.parents[1])),
                          "sha256": hashlib.sha256(prelude_data).hexdigest()})


def replace_checked(source, old, new, module):
    count = source.count(old)
    if count:
        compatibility.append({"module": module, "old": old, "new": new, "count": count})
    return source.replace(old, new)


for module in ordered:
    record = records[module]
    path = BASE / "source" / pathlib.PurePosixPath(record["path"].removeprefix("lean/"))
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != record["sha256"]:
        raise ValueError(f"Modified upstream source: {module}")
    source = re.sub(r"^import[^\n]*\n", "", data.decode("utf-8"), flags=re.M)
    if re.search(r"\b(sorry|admit)\b|^axiom\s", source, re.M):
        raise ValueError(f"Unproved declaration: {module}")
    # Only complete identifiers are renamed; iff lemmas retain their names.
    for old, new in [("ite_eq_left", "if_pos"), ("ite_eq_right", "if_neg"),
                     ("dite_eq_left", "dif_pos"), ("dite_eq_right", "dif_neg"),
                     ("Matrix.det_of_isUpperTriangular", "Matrix.det_of_upperTriangular")]:
        count = len(re.findall(r"\b" + re.escape(old) + r"\b", source))
        if count:
            source = re.sub(r"\b" + re.escape(old) + r"\b", new, source)
            compatibility.append({"module": module, "old": old, "new": new, "count": count})
    source = replace_checked(source, "convert! Complex.exp_pi_div_two_mul_I using 2",
                             "convert Complex.exp_pi_div_two_mul_I using 2", module)
    source = replace_checked(source, "    rw [chops _ _ _ (diy a),hg.2.1,chops _ _ _ (diy b)] at hD",
                             "    dsimp only at hD hM\n    rw [chops _ _ _ (diy a),hg.2.1,chops _ _ _ (diy b)] at hD", module)
    source = replace_checked(source, "(by intro i; unfold P; split <;> simp_all)",
                             "(by intro i; unfold P; dsimp only; split <;> simp_all)", module)
    source = replace_checked(source, "intro i j hj; unfold deal; split <;> omega",
                             "intro i j hj; unfold deal; dsimp only; split <;> omega", module)
    source = replace_checked(source, "(HD.congr fun i => by rw [spray,show extent",
                             "(HD.congr fun i => by dsimp only [spray]; rw [show extent", module)
    source = replace_checked(source, "have hh := h.volume_ge i.i; have hk := i.hj; omega)",
                             "change i.j < N i.i\n      have hh := h.volume_ge i.i; have hk := i.hj; omega)", module)
    chunks.append(f"\n/- Upstream module {module}; sha256 {record['sha256']}. -/\n"
                  f"section\n{source}\nend\n")
chunks.append("\n#print axioms OAI.PowerSaving.transform_main\n"
              "#print axioms OAI.PowerSaving.convolution_main\n"
              "#print axioms OAI.PowerSaving.transform_main_order\n"
              "#print axioms OAI.PowerSaving.convolution_main_order\n")
target = BASE.parents[1] / "formalization" / "vendor" / "OpenAIUniformFourierBundle.lean"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text("".join(chunks), encoding="utf-8")
(BASE / "compatibility_manifest.json").write_text(json.dumps({
    "upstream_commit": manifest["commit"], "target_lean_mathlib": "4.29.1",
    "native_checked": False, "mathlib_imports": mathlib_imports, "edits": compatibility,
    "bundle_sha256": hashlib.sha256(target.read_bytes()).hexdigest()
}, indent=2) + "\n", encoding="utf-8")
print(json.dumps({"bundle": str(target), "modules": len(ordered),
                  "bytes": target.stat().st_size, "native_checked": False}))
